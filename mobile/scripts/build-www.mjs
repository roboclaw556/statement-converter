// Builds www/ for Capacitor: the mobile UI, the shared converter (../src/core),
// pdf.js and tesseract.js with its English model, all bundled so the app works
// offline and statements never leave the phone. No bundler: plain ES modules.
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const HERE = join(dirname(fileURLToPath(import.meta.url)), '..');
const REPO = join(HERE, '..');
const WWW = join(HERE, 'www');
const require = createRequire(join(HERE, 'package.json'));
const pkgDir = (name) => dirname(require.resolve(name + '/package.json'));

rmSync(WWW, { recursive: true, force: true });
mkdirSync(WWW, { recursive: true });
cpSync(join(HERE, 'src'), WWW, { recursive: true });

// shared converter, read only (owned by the web app)
mkdirSync(join(WWW, 'core'));
for (const f of readdirSync(join(REPO, 'src/core')).filter((f) => f.endsWith('.js'))) {
  cpSync(join(REPO, 'src/core', f), join(WWW, 'core', f));
}

// pdf.js (same version as the web app)
const pdfjs = join(pkgDir('pdfjs-dist'), 'build');
mkdirSync(join(WWW, 'vendor'), { recursive: true });
for (const f of ['pdf.min.mjs', 'pdf.worker.min.mjs']) cpSync(join(pdfjs, f), join(WWW, 'vendor', f));

// tesseract.js: worker, LSTM-only wasm cores (plain, SIMD, relaxed SIMD) and the English model
const t = join(WWW, 'vendor/tesseract');
mkdirSync(join(t, 'core'), { recursive: true });
mkdirSync(join(t, 'lang'), { recursive: true });
cpSync(join(pkgDir('tesseract.js'), 'dist/tesseract.esm.min.js'), join(t, 'tesseract.esm.min.js'));
cpSync(join(pkgDir('tesseract.js'), 'dist/worker.min.js'), join(t, 'worker.min.js'));
for (const f of ['tesseract-core-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js', 'tesseract-core-relaxedsimd-lstm.wasm.js']) {
  cpSync(join(pkgDir('tesseract.js-core'), f), join(t, 'core', f));
}
cpSync(join(pkgDir('@tesseract.js-data/eng'), '4.0.0_best_int/eng.traineddata.gz'), join(t, 'lang/eng.traineddata.gz'));

// config from the site's brand file plus optional build-time env (public keys only)
const site = JSON.parse(readFileSync(join(REPO, 'seo/site.json'), 'utf8'));
const config = {
  brand: site.brand,
  site: site.domain,
  apiBase: process.env.API_BASE || site.domain,
  revenuecat: {
    ios: process.env.REVENUECAT_IOS_KEY || '',
    android: process.env.REVENUECAT_ANDROID_KEY || '',
  },
  version: JSON.parse(readFileSync(join(HERE, 'package.json'), 'utf8')).version,
};
writeFileSync(join(WWW, 'config.js'), `// generated by scripts/build-www.mjs\nexport const CONFIG = ${JSON.stringify(config, null, 2)};\n`);
const html = readFileSync(join(WWW, 'index.html'), 'utf8').replaceAll('{{brand}}', site.brand);
writeFileSync(join(WWW, 'index.html'), html);
if (!existsSync(join(WWW, 'core/plans.js'))) throw new Error('src/core/plans.js is missing');
console.log('www/ built for', site.brand);
